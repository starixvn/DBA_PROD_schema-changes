--------------------------------------------script generate commands------------------------------------------------
use master
go
drop table if exists #tmp
SELECT sp.[name], sp.[sid] [SID_DB053], sp2.[sid] [SID_DB052]
,(select distinct string_agg(concat(ssperm.[state_desc],' ',ssperm.[permission_name]),' TO ; ')
from sys.server_permissions ssperm
where ssperm.grantee_principal_id = sp.principal_id)+' ;'  as 'serverPermission'
,(select string_agg(px.name,',') from sys.server_role_members rm join sys.server_principals px on rm.role_principal_id = px.principal_id where rm.member_principal_id=sp.principal_id) as 'serverRole'
into #tmp
FROM sys.server_principals AS sp
	inner join DB052.master.sys.server_principals AS sp2 on sp.name = sp2.name
where sp.[sid] <> sp2.[sid]
and sp.[name] not like '%#%'
and sp.[name] not like '%cert_user%'

select * from #tmp

select 'drop login ['+ [name] + ']' from #tmp

select 'CREATE LOGIN ['+[name]+'] WITH PASSWORD = ',LOGINPROPERTY([name],'PASSWORDHASH'), ' HASHED, SID = ',[SID_DB052],', DEFAULT_DATABASE = [master], CHECK_POLICY = OFF, CHECK_EXPIRATION = OFF ' from #tmp

select 'ALTER SERVER ROLE ',serverRole,' ADD MEMBER ',[name] from #tmp where serverRole is not null

select replace(serverPermission,';',[name] collate Latin1_General_CI_AS_KS_WS + ';') from #tmp

